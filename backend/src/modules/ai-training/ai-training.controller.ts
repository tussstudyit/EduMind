import { Body, Controller, Delete, Get, Param, Patch, Post, Query, UseGuards } from '@nestjs/common';
import { CurrentUser } from '../../common/decorators/current-user.decorator';
import { Roles } from '../../common/decorators/roles.decorator';
import { JwtAuthGuard } from '../../common/guards/jwt-auth.guard';
import { RolesGuard } from '../../common/guards/roles.guard';
import { UserEntity } from '../users/user.entity';
import { AiTrainingService } from './ai-training.service';

@Controller('ai-training')
@UseGuards(JwtAuthGuard, RolesGuard)
export class AiTrainingController {
  constructor(private readonly training: AiTrainingService) {}

  // 1. Corpus (Student & Teacher document uploads -> AI knowledge base)
  @Get('corpus')
  listCorpus(@CurrentUser() user: UserEntity, @Query('status') status?: string) {
    return this.training.listCorpus(user, status);
  }

  @Post('corpus')
  uploadCorpus(
    @CurrentUser() user: UserEntity,
    @Body()
    body: {
      id?: string;
      title: string;
      description?: string;
      subject: string;
      category?: string;
      fileName: string;
      mimeType?: string;
      fileSize?: number;
      extractedText?: string;
    },
  ) {
    return this.training.uploadToCorpus(user, body);
  }

  @Patch('corpus/:id/review')
  @Roles('admin', 'teacher')
  reviewCorpus(
    @CurrentUser() user: UserEntity,
    @Param('id') id: string,
    @Body()
    body: {
      status: 'approved' | 'indexed' | 'rejected';
      reviewNotes?: string;
      includedInTraining?: boolean;
      autoGenerateDataset?: boolean;
    },
  ) {
    return this.training.reviewCorpusDocument(user, id, body);
  }

  @Delete('corpus/:id')
  deleteCorpus(@CurrentUser() user: UserEntity, @Param('id') id: string) {
    return this.training.deleteCorpusDocument(user, id);
  }

  // 2. Labeled Datasets
  @Get('datasets')
  @Roles('admin', 'teacher')
  listDatasets(@Query('status') status?: string, @Query('subject') subject?: string) {
    return this.training.listDatasets(status, subject);
  }

  @Post('datasets')
  @Roles('admin', 'teacher')
  createDataset(
    @CurrentUser() user: UserEntity,
    @Body()
    body: {
      subject: string;
      prompt: string;
      expectedResponse: string;
      systemPrompt?: string;
      tags?: string[];
      qualityScore?: number;
      status?: 'draft' | 'labeled' | 'validated';
      sourceType?: string;
    },
  ) {
    return this.training.createDatasetEntry(user, body);
  }

  @Patch('datasets/:id')
  @Roles('admin', 'teacher')
  updateDataset(
    @CurrentUser() user: UserEntity,
    @Param('id') id: string,
    @Body()
    body: Partial<{
      subject: string;
      prompt: string;
      expectedResponse: string;
      systemPrompt: string;
      tags: string[];
      qualityScore: number;
      status: 'draft' | 'labeled' | 'validated' | 'archived';
    }>,
  ) {
    return this.training.updateDatasetEntry(user, id, body);
  }

  @Delete('datasets/:id')
  @Roles('admin', 'teacher')
  deleteDataset(@Param('id') id: string) {
    return this.training.deleteDatasetEntry(id);
  }

  @Post('datasets/harvest')
  @Roles('admin', 'teacher')
  harvestDatasets(@CurrentUser() user: UserEntity) {
    return this.training.harvestDatasetFromLms(user);
  }

  @Get('datasets/export-jsonl')
  @Roles('admin', 'teacher')
  exportJsonl() {
    return this.training.exportDatasetJsonl();
  }

  // 3. Training Jobs Queue
  @Get('jobs')
  @Roles('admin', 'teacher')
  listJobs() {
    return this.training.listJobs();
  }

  @Post('jobs')
  @Roles('admin')
  startJob(
    @CurrentUser() user: UserEntity,
    @Body()
    body: {
      name: string;
      baseModel?: string;
      targetModelName?: string;
      hyperparameters?: {
        epochs?: number;
        learningRate?: number;
        batchSize?: number;
        loraRank?: number;
      };
    },
  ) {
    return this.training.startTrainingJob(user, body);
  }

  @Post('jobs/:id/cancel')
  @Roles('admin')
  cancelJob(@CurrentUser() user: UserEntity, @Param('id') id: string) {
    return this.training.cancelJob(user, id);
  }

  // 4. Model Versions, Evaluation & Deployment
  @Get('models')
  @Roles('admin', 'teacher')
  listModels() {
    return this.training.listModelVersions();
  }

  @Post('models/:id/deploy')
  @Roles('admin')
  deployModel(@CurrentUser() user: UserEntity, @Param('id') id: string) {
    return this.training.deployModelVersion(user, id);
  }

  @Post('models/:id/evaluate')
  @Roles('admin', 'teacher')
  evaluateModel(
    @CurrentUser() user: UserEntity,
    @Param('id') id: string,
    @Body() body?: { testPrompt?: string },
  ) {
    return this.training.evaluateModelVersion(user, id, body?.testPrompt);
  }
}
