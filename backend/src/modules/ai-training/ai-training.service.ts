  async createDatasetEntry(
    user: UserEntity,
    body: {
      subject: string;
      prompt: string;
      expectedResponse: string;
      systemPrompt?: string;
      tags?: string[];
      qualityScore?: number;
      status?: 'draft' | 'labeled' | 'validated';
      sourceType?: string;
    },
  ) {
    const entry = this.datasets.create({
      id: createId('ds'),
      sourceType: body.sourceType || 'manual',
      subject: body.subject?.trim() || 'Tổng hợp',
      prompt: body.prompt.trim(),
      expectedResponse: body.expectedResponse.trim(),
      systemPrompt:
        body.systemPrompt?.trim() ||
        'Bạn là EduMind AI Tutor — trợ lý học tập thông minh của nhà trường.',
      tags: body.tags?.length ? body.tags : [body.subject || 'edumind'],
      qualityScore: String(body.qualityScore ?? 0.95),
      status: body.status || 'validated',
      createdBy: user.id,
    });
    return this.datasets.save(entry);
  }

  async updateDatasetEntry(
    _user: UserEntity,
    id: string,
    body: Partial<{
      subject: string;
      prompt: string;
      expectedResponse: string;
      systemPrompt: string;
      tags: string[];
      qualityScore: number;
      status: 'draft' | 'labeled' | 'validated' | 'archived';
    }>,
  ) {
    const entry = await this.datasets.findOneBy({ id });
    if (!entry) throw new NotFoundException('Không tìm thấy mẫu dữ liệu gán nhãn.');
    if (body.subject !== undefined) entry.subject = body.subject.trim();
    if (body.prompt !== undefined) entry.prompt = body.prompt.trim();
    if (body.expectedResponse !== undefined) entry.expectedResponse = body.expectedResponse.trim();
    if (body.systemPrompt !== undefined) entry.systemPrompt = body.systemPrompt.trim();
    if (body.tags !== undefined) entry.tags = body.tags;
    if (body.qualityScore !== undefined) entry.qualityScore = String(body.qualityScore);
    if (body.status !== undefined) entry.status = body.status;
    return this.datasets.save(entry);
  }

  async deleteDatasetEntry(id: string) {
    const entry = await this.datasets.findOneBy({ id });
    if (!entry) throw new NotFoundException('Không tìm thấy mẫu dữ liệu.');
    await this.datasets.remove(entry);
    return { deleted: true };
  }

  /**
   * Tự động thu thập & tổng hợp dữ liệu gán nhãn từ Bài giảng, Ngân hàng Câu hỏi và Kho tài liệu đã duyệt
   */
  async harvestDatasetFromLms(user: UserEntity) {
    const [publishedLessons, quizQuestions, approvedCorpus] = await Promise.all([
      this.lessons.find({ where: { isPublished: true }, take: 10 }),
      this.questions.find({ take: 15 }),
      this.corpus.find({ where: [{ status: 'approved' }, { status: 'indexed' }], take: 10 }),
    ]);

    const existingPrompts = new Set(
      (await this.datasets.find({ select: { prompt: true } })).map((d) => d.prompt.toLowerCase()),
    );

    const newEntries: AiDatasetEntryEntity[] = [];

    for (const lesson of publishedLessons) {
      const prompt = `Giải thích nội dung bài học: "${lesson.title}"`;
      if (!existingPrompts.has(prompt.toLowerCase()) && lesson.contentMarkdown) {
        newEntries.push(
          this.datasets.create({
            id: createId('ds'),
            sourceType: 'document',
            sourceId: lesson.id,
            subject: 'Bài giảng khóa học',
            prompt,
            expectedResponse: `${lesson.description ? `**Tóm tắt:** ${lesson.description}\n\n` : ''}${lesson.contentMarkdown}`,
            systemPrompt: 'Bạn là EduMind AI Tutor giải thích bài giảng chính khóa.',
            tags: ['lesson', 'curriculum'],
            qualityScore: '0.95',
            status: 'validated',
            createdBy: user.id,
          }),
        );
        existingPrompts.add(prompt.toLowerCase());
      }
    }

    for (const q of quizQuestions) {
      const prompt = q.content.trim();
      if (!existingPrompts.has(prompt.toLowerCase())) {
        const correctOpt = (q.options || []).find((o) => o.isCorrect);
        const answerText = correctOpt
          ? `**Đáp án chính xác:** ${correctOpt.text}\n\n**Giải thích:** ${q.explanation || 'Phương án này thỏa mãn đầy đủ yêu cầu lý thuyết của câu hỏi.'}`
          : q.explanation || 'Trình bày theo các bước lý thuyết và ví dụ thực hành trong bài giảng.';
        newEntries.push(
          this.datasets.create({
            id: createId('ds'),
            sourceType: 'quiz',
            sourceId: q.id,
            subject: 'Ngân hàng Đề thi',
            prompt,
            expectedResponse: answerText,
            systemPrompt: 'Bạn là EduMind AI Tutor hướng dẫn giải đề kiểm tra.',
            tags: ['quiz', q.type],
            qualityScore: '0.96',
            status: 'validated',
            createdBy: user.id,
          }),
        );
        existingPrompts.add(prompt.toLowerCase());
      }
    }

    for (const doc of approvedCorpus) {
      const prompt = `Tóm tắt tài liệu thư viện: "${doc.title}" (${doc.subject})`;
      if (!existingPrompts.has(prompt.toLowerCase())) {
        newEntries.push(
          this.datasets.create({
            id: createId('ds'),
            sourceType: 'document',
            sourceId: doc.id,
            subject: doc.subject || 'Thư viện',
            prompt,
            expectedResponse: `**Tài liệu:** ${doc.title} (${doc.category})\n**Nội dung chính:**\n${doc.extractedText || doc.description}`,
            systemPrompt: 'Bạn là EduMind AI Tutor trích xuất tri thức từ kho tài liệu sinh viên & giảng viên.',
            tags: [doc.subject, 'student-corpus'].filter(Boolean),
            qualityScore: '0.93',
            status: 'labeled',
            createdBy: user.id,
          }),
        );
        existingPrompts.add(prompt.toLowerCase());
      }
    }

    if (newEntries.length > 0) {
      await this.datasets.save(newEntries);
    }

    await this.audit.write(
      'AI_DATASET_HARVESTED',
      `${user.name} đã thu thập và gán nhãn tự động ${newEntries.length} mẫu huấn luyện từ Bài giảng, Đề thi và Kho tài liệu.`,
      user,
    );

    return {
      addedCount: newEntries.length,
      totalCount: await this.datasets.count(),
    };
  }

  async exportDatasetJsonl() {
    const entries = await this.datasets.find({
      where: [{ status: 'validated' }, { status: 'labeled' }],
      order: { createdAt: 'ASC' },
    });

    const lines = entries.map((e) =>
      JSON.stringify({
        messages: [
          {
            role: 'system',
            content:
              e.systemPrompt ||
              'Bạn là EduMind AI Tutor — trợ lý học tập đại học thông minh.',
          },
          { role: 'user', content: e.prompt },
          { role: 'assistant', content: e.expectedResponse },
        ],
        metadata: {
          id: e.id,
          subject: e.subject,
          qualityScore: Number(e.qualityScore),
          tags: e.tags,
        },
      }),
    );

    return {
      count: entries.length,
      format: 'jsonl',
      content: lines.join('\n'),
    };
  }

