  // ==========================================================================
  // 1. KHO DỮ LIỆU & TÀI LIỆU SINH VIÊN / GIẢNG VIÊN (AI CORPUS)
  // ==========================================================================
  async listCorpus(user: UserEntity, status?: string) {
    const qb = this.corpus.createQueryBuilder('doc');
    if (status && status !== 'all') {
      qb.andWhere('doc.status = :status', { status });
    }
    if (user.role === 'student') {
      qb.andWhere('(doc.uploaderId = :uid OR doc.status IN (:...publicStatuses))', {
        uid: user.id,
        publicStatuses: ['approved', 'indexed'],
      });
    }
    return qb.orderBy('doc.createdAt', 'DESC').getMany();
  }

  async uploadToCorpus(
    user: UserEntity,
    data: {
      id?: string;
      title: string;
      description?: string;
      subject: string;
      category?: string;
      fileName: string;
      mimeType?: string;
      fileSize?: number;
      extractedText?: string;
    },
  ) {
    const extracted = (data.extractedText || '').trim();
    const chunkCount = Math.max(1, Math.ceil((extracted.length || 400) / 500));
    const isStaff = user.role === 'admin' || user.role === 'teacher';

    const doc = this.corpus.create({
      id: data.id?.trim() || createId('corpus'),
      uploaderId: user.id,
      uploaderName: user.name || 'Học viên EduMind',
      uploaderRole: user.role,
      title: data.title.trim(),
      description: data.description?.trim() || '',
      subject: data.subject.trim() || 'Tổng hợp',
      category: data.category?.trim() || 'Ghi chú học tập',
      fileName: data.fileName.trim(),
      mimeType: data.mimeType || 'application/octet-stream',
      fileSize: Number(data.fileSize) || 0,
      extractedText:
        extracted ||
        `Tài liệu học tập: ${data.title.trim()} (${data.subject.trim()}). ${data.description?.trim() || ''}`,
      chunkCount,
      status: isStaff ? 'indexed' : 'pending_review',
      reviewedBy: isStaff ? user.name : null,
      reviewNotes: isStaff ? 'Tự động duyệt và lập chỉ mục cho giảng viên/quản trị viên.' : null,
      includedInTraining: isStaff,
    });

    const saved = await this.corpus.save(doc);

    // Nếu là tài liệu của giảng viên/admin, tự động trích xuất cặp Q&A vào dataset
    if (isStaff) {
      await this.extractDatasetPairsFromDocument(saved, user.id);
    }

    return saved;
  }

  async reviewCorpusDocument(
    user: UserEntity,
    id: string,
    body: {
      status: 'approved' | 'indexed' | 'rejected';
      reviewNotes?: string;
      includedInTraining?: boolean;
      autoGenerateDataset?: boolean;
    },
  ) {
    const doc = await this.corpus.findOneBy({ id });
    if (!doc) throw new NotFoundException('Không tìm thấy tài liệu trong kho dữ liệu.');

    doc.status = body.status;
    doc.reviewedBy = user.name;
    doc.reviewNotes =
      body.reviewNotes?.trim() ||
      (body.status === 'rejected'
        ? 'Tài liệu chưa đạt chuẩn chất lượng huấn luyện.'
        : 'Đã kiểm duyệt và đưa vào kho tri thức AI.');
    doc.includedInTraining =
      body.status === 'rejected' ? false : (body.includedInTraining ?? true);

    const saved = await this.corpus.save(doc);
    let generatedPairs = 0;

    if (
      (body.status === 'approved' || body.status === 'indexed') &&
      (body.autoGenerateDataset ?? true)
    ) {
      const pairs = await this.extractDatasetPairsFromDocument(saved, user.id);
      generatedPairs = pairs.length;
    }

    await this.audit.write(
      'AI_CORPUS_REVIEWED',
      `${user.name} đã cập nhật trạng thái tài liệu "${doc.title}" sang [${body.status.toUpperCase()}] (Sinh ${generatedPairs} mẫu huấn luyện).`,
      user,
    );

    return { document: saved, generatedPairs };
  }

  async deleteCorpusDocument(user: UserEntity, id: string) {
    const doc = await this.corpus.findOneBy({ id });
    if (!doc) throw new NotFoundException('Không tìm thấy tài liệu.');
    if (user.role === 'student' && doc.uploaderId !== user.id) {
      throw new ForbiddenException('Bạn không có quyền xóa tài liệu này.');
    }
    await this.corpus.remove(doc);
    return { deleted: true };
  }

  private async extractDatasetPairsFromDocument(
    doc: AiCorpusDocumentEntity,
    actorId: string,
  ): Promise<AiDatasetEntryEntity[]> {
    const text = (doc.extractedText || `${doc.title}. ${doc.description}`).trim();
    const paragraphs = text
      .split(/\n{2,}|\r\n\r\n/)
      .map((p) => p.trim())
      .filter((p) => p.length >= 40)
      .slice(0, 3);

    const entries: AiDatasetEntryEntity[] = [];
    if (paragraphs.length === 0) {
      paragraphs.push(`${doc.title}: ${doc.description || text}`);
    }

    for (let i = 0; i < paragraphs.length; i++) {
      const para = paragraphs[i];
      const entry = this.datasets.create({
        id: createId('ds'),
        sourceType: 'document',
        sourceId: doc.id,
        subject: doc.subject || 'Tổng hợp',
        prompt:
          i === 0
            ? `Hãy giải thích và tóm tắt nội dung cốt lõi của tài liệu "${doc.title}" thuộc môn ${doc.subject}.`
            : `Trong tài liệu "${doc.title}" (${doc.subject}), phần kiến thức sau được hiểu và áp dụng như thế nào: "${para.slice(0, 90)}..."?`,
        expectedResponse: `**Kiến thức từ học liệu "${doc.title}" (${doc.subject}):**\n\n${para}\n\n**Tổng kết áp dụng:** Nắm vững định nghĩa và quy tắc trên giúp giải quyết chính xác các bài toán thực hành trong môn ${doc.subject}.`,
        systemPrompt: 'Bạn là EduMind AI Tutor được huấn luyện trên kho học liệu chính quy của nhà trường.',
        tags: [doc.subject, doc.category, 'corpus-verified'].filter(Boolean),
        qualityScore: '0.94',
        status: 'validated',
        createdBy: actorId,
      });
      entries.push(entry);
    }

    return this.datasets.save(entries);
  }

