  async deployModelVersion(user: UserEntity, id: string) {
    const target = await this.models.findOneBy({ id });
    if (!target) throw new NotFoundException('Không tìm thấy phiên bản mô hình.');

    const allModels = await this.models.find();
    for (const m of allModels) {
      if (m.id === target.id) {
        m.isDeployed = true;
        m.status = 'active';
        m.deployedAt = new Date();
        m.deployedBy = user.name;
      } else if (m.isDeployed) {
        m.isDeployed = false;
        m.status = 'rollback';
      }
    }
    await this.models.save(allModels);

    // Đồng bộ sang AiConfigEntity để AI Tutor & toàn hệ thống sử dụng phiên bản này
    const config = await this.aiEngine.getActiveConfig();
    config.activeModelVersionId = target.id;
    config.modelName = target.modelIdentifier;
    config.serviceStatus = 'healthy';
    await this.aiConfigs.save(config);

    await this.audit.write(
      'AI_MODEL_DEPLOYED',
      `${user.name} đã triển khai phiên bản model "${target.modelIdentifier}" (${target.versionTag}) làm mô hình chính thức trên toàn hệ thống.`,
      user,
    );

    return target;
  }

  async evaluateModelVersion(user: UserEntity, id: string, testPrompt?: string) {
    const target = await this.models.findOneBy({ id });
    if (!target) throw new NotFoundException('Không tìm thấy phiên bản mô hình.');

    const promptToRun =
      testPrompt?.trim() ||
      'Giải thích ngắn gọn cách hoạt động của vòng lặp for kèm độ phức tạp và cho 1 ví dụ Python.';

    const start = Date.now();
    const reply = await this.aiEngine.generateTutorReply({
      studentId: user.id,
      conversationTitle: `Benchmark ${target.versionTag}`,
      history: [],
      userMessage: promptToRun,
    });
    const latencyMs = Date.now() - start;

    target.metrics = {
      ...target.metrics,
      avgLatencyMs: Math.round((target.metrics.avgLatencyMs + latencyMs) / 2),
    };
    await this.models.save(target);

    return {
      modelVersion: target,
      testPrompt: promptToRun,
      response: reply.content,
      measuredLatencyMs: latencyMs,
      passedThreshold: target.metrics.accuracy >= 85,
    };
  }
